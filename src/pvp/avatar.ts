export function avatarFrameUrl(frameId: string | undefined | null): string | null {
  if (!frameId) return null;
  const file = FRAME_ID_TO_FILE[frameId];
  if (!file) return null;
  return new URL(`../assets/avatar-frames/${file}`, import.meta.url).href;
}
